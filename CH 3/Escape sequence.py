# Python Escape Sequence Chart

sentence = "Harry is a good\tboy\nbut he is fool. "
print(sentence)

print("Hello world\\")

#🔑 Most Useful Escape Characters

#\n → New Line
print("Hello\nWorld")

#\t → Tab Space
print("Hello\tWorld")

#\\ → Backslash
print("This is a backslash: \\")

#\' → Single Quote
print('It\'s easy')

#\" → Double Quote
print("He said \"Hello\"")

#\r → Carriage Return (overwrite line)
print("Hello\rWorld")

#\b → Backspace
print("Helloo\b")

