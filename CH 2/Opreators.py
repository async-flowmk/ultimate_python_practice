# Arithmetic operators
a = 10
b = 3
print(a + b)  # Additio
print(a - b)  # Subtraction
print(a * b)  # Multiplication
print(a / b)  # Division
print(a % b)  # Modulus (It gives the remainder after division.)
print(a ** b)  # Exponentiation
print(a // b)  # Floor division

# Assignment operators
x = 5
x += 2  # Equivalent to x = x + 2
print(x)  # Output: 7
x -= 3  # Equivalent to x = x - 3
print(x)  # Output: 4
x *= 4  # Equivalent to x = x * 4
print(x)  # Output: 16

# Comparison operators
print (a == x) # Equality
print(a > b) # Greater than
print(a < b) # Less than
print(a >= b) # Greater than or equal to
print(a <= b) # Less than or equal to
print(a != b) # Not equal to

# Logical operators

# OR operator returns True if at least one of the conditions is true.
# AND operator returns True only if both conditions are true.   
# NOT operator returns True if the condition is false, and False if the condition is true.

p = True
q = False  

print(p or q)  # Output: True
print(p and q)  # Output: False
print(p and p)  # Output: True
print(not p)    # Output: False     
print(not q)    # Output: True

