# RULES OF VARIABLES
# 1. A variable name must start with a letter or the underscore character.
# 2. A variable name cannot start with a number.
# 3. A variable name can only contain alpha-numeric characters and underscores (A-z, 0-9, and _).
# 4. Variable names are case-sensitive (age, Age and AGE are three different variables).
# 5. Variable names cannot be the same as reserved keywords in Python (like if, else, while, etc.).     
# 6. Variable names should be descriptive and meaningful to enhance code readability.

# Examples of valid variable names
name = "Dr Doom" 
age = 44
_power = "Magician"

# Examples of invalid variable names
# 1name = "Invalid" # Invalid: starts with a number     
# @name = "Invalid" # Invalid: starts with a special character
# name! = "Invalid" # Invalid: contains a special character


